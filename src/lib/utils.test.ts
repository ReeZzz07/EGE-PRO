// Общие чистые утилиты — checkAnswer/normalizeAnswer особенно критичны: это сам критерий
// "правильно/неправильно" для ответов ЕГЭ по всей платформе (SolveView/MockExam/дневник ошибок).
// Ошибка здесь не падает с исключением — она молча засчитывает верный ответ неверным (или наоборот),
// и это может остаться незамеченным очень долго.
import { describe, expect, it } from "vitest";
import { checkAnswer, dateKey, dayIndex, formatClock, formatDay, normalizeAnswer, plural, safeMathEval } from "./utils";

describe("normalizeAnswer", () => {
  it("регистр, ё→е, запятая→точка, лишние пробелы, разные тире→дефис", () => {
    expect(normalizeAnswer("ЁЖИК")).toBe("ежик");
    expect(normalizeAnswer("3,14")).toBe("3.14");
    expect(normalizeAnswer("a  −  b — c")).toBe("a - b - c");
    expect(normalizeAnswer("  Ответ  ")).toBe("ответ");
  });
});

describe("checkAnswer", () => {
  it("точное совпадение после нормализации — верно", () => {
    expect(checkAnswer("Москва", ["москва"])).toBe(true);
    expect(checkAnswer("3,5", ["3.5"])).toBe(true);
  });

  it("несовпадение — неверно", () => {
    expect(checkAnswer("Санкт-Петербург", ["Москва"])).toBe(false);
  });

  it("пустой ответ — всегда неверно, даже если пустая строка технически «принята»", () => {
    expect(checkAnswer("", ["", "москва"])).toBe(false);
    expect(checkAnswer("   ", ["москва"])).toBe(false);
  });

  // Задания с множественным выбором хранят эталонный ответ в БД СЛИТНО («145», без разделителей —
  // так записаны реально все ~22 тыс. подобных ответов в банке, ни один не через запятую) — ученик,
  // естественно набравший свой ответ через запятую («1,4,5»), должен получить «верно», а не
  // «неверно» только из-за формата записи (было реальным багом — normalizeAnswer превращает
  // запятую в точку, а digitsOnly её не убирала; см. историю коммитов).
  it("ответ через запятую засчитывается против слитного эталона из БД (реальный формат банка)", () => {
    expect(checkAnswer("1, 4, 5", ["145"])).toBe(true);
    expect(checkAnswer("13", ["145"])).toBe(false); // не любой набор цифр — только совпадающий состав
  });

  // Эталонный ответ, ЗАПИСАННЫЙ через запятую («1,3»), в банке ЕГЭ-ПРО не встречается для
  // наборов цифр (только для десятичных дробей вроде «0,5») — намеренно НЕ покрываем эту форму
  // свёрткой: после normalizeAnswer «1,3» неотличимо от десятичной дроби «1.3» (см. следующий тест),
  // а безопасный выбор в этой неоднозначности — не выдавать ложное «верно» для дробей.
  it("эталон через запятую («1,3») трактуется как возможная дробь, а не как набор цифр — свёртка не применяется", () => {
    expect(checkAnswer("13", ["1,3"])).toBe(false);
  });

  // Риск коллизии, из-за которого нельзя было просто всегда убирать точку: если эталонный ответ —
  // ДЕСЯТИЧНАЯ дробь (точка после normalizeAnswer значима, не разделитель списка), то дропнутая
  // учеником точка не должна засчитываться как верный ответ — «13» ≠ «1.3» по величине. В банке
  // ~2300 подобных дробных эталонов (математика/физика/химия/биология/география), где реален риск
  // случайного совпадения с "digit-set"-эвристикой выше.
  it("десятичная дробь как эталонный ответ — НЕ участвует в свёртке набора цифр, дропнутая точка не засчитывается", () => {
    expect(checkAnswer("13", ["1.3"])).toBe(false);
    expect(checkAnswer("5", ["0.5"])).toBe(false);
    expect(checkAnswer("1.3", ["1.3"])).toBe(true); // точный ввод дроби по-прежнему работает
    expect(checkAnswer("1,3", ["1.3"])).toBe(true); // и через запятую — тоже (точное совпадение после нормализации)
  });

  it("несколько принятых вариантов — достаточно совпадения хотя бы с одним", () => {
    expect(checkAnswer("б", ["а", "б", "в"])).toBe(true);
    expect(checkAnswer("г", ["а", "б", "в"])).toBe(false);
  });

  it("порядок цифр в наборе имеет значение (не сортируется) — «31» ≠ «13»", () => {
    expect(checkAnswer("31", ["13"])).toBe(false);
  });
});

describe("formatClock", () => {
  it("минуты и секунды с ведущим нулём", () => {
    expect(formatClock(0)).toBe("00:00");
    expect(formatClock(65)).toBe("01:05");
    expect(formatClock(3599)).toBe("59:59");
  });

  it("минуты не ограничены 59 (общий счётчик, не часы:минуты)", () => {
    expect(formatClock(3600)).toBe("60:00");
  });
});

describe("plural", () => {
  it("русские формы множественного числа: 1/2-4/5-20 и «-надцать»", () => {
    expect(plural(1, "задание", "задания", "заданий")).toBe("задание");
    expect(plural(2, "задание", "задания", "заданий")).toBe("задания");
    expect(plural(4, "задание", "задания", "заданий")).toBe("задания");
    expect(plural(5, "задание", "задания", "заданий")).toBe("заданий");
    expect(plural(0, "задание", "задания", "заданий")).toBe("заданий");
  });

  it("11-19 — всегда «много», несмотря на последнюю цифру (11 не «одно», 12 не «два»)", () => {
    expect(plural(11, "задание", "задания", "заданий")).toBe("заданий");
    expect(plural(12, "задание", "задания", "заданий")).toBe("заданий");
    expect(plural(19, "задание", "задания", "заданий")).toBe("заданий");
  });

  it("21/22/25 — форма зависит от последней цифры, как и без десятков (не 11-19)", () => {
    expect(plural(21, "задание", "задания", "заданий")).toBe("задание");
    expect(plural(22, "задание", "задания", "заданий")).toBe("задания");
    expect(plural(25, "задание", "задания", "заданий")).toBe("заданий");
  });
});

describe("dayIndex", () => {
  it("детерминирован и стабилен в пределах одного вызова, в границах [0, len)", () => {
    const idx = dayIndex(7);
    expect(idx).toBeGreaterThanOrEqual(0);
    expect(idx).toBeLessThan(7);
    expect(dayIndex(7)).toBe(idx); // тот же день — тот же индекс
  });
});

describe("dateKey / formatDay", () => {
  it("dateKey — один и тот же день даёт один и тот же ключ независимо от времени суток", () => {
    const morning = new Date(2026, 2, 15, 3, 0, 0).getTime();
    const evening = new Date(2026, 2, 15, 23, 59, 0).getTime();
    expect(dateKey(morning)).toBe(dateKey(evening));
  });

  it("dateKey — разные дни дают разные ключи", () => {
    const day1 = new Date(2026, 2, 15).getTime();
    const day2 = new Date(2026, 2, 16).getTime();
    expect(dateKey(day1)).not.toBe(dateKey(day2));
  });

  it("formatDay возвращает непустую человекочитаемую дату", () => {
    expect(formatDay(Date.now()).length).toBeGreaterThan(0);
  });
});

describe("safeMathEval", () => {
  it("базовая арифметика с приоритетом операций и скобками", () => {
    expect(safeMathEval("2+2")).toBe(4);
    expect(safeMathEval("2+3*4")).toBe(14);
    expect(safeMathEval("(2+3)*4")).toBe(20);
    expect(safeMathEval("2^10")).toBe(1024);
    expect(safeMathEval("-5+3")).toBe(-2);
  });

  it("десятичные числа через точку — поддерживаются; через запятую — нет (не путать с normalizeAnswer)", () => {
    expect(safeMathEval("1.5+1.5")).toBe(3);
    expect(safeMathEval("1,5+1,5")).toBeNull();
  });

  it("деление на ноль — NaN, а не исключение", () => {
    expect(safeMathEval("1/0")).toBeNaN();
  });

  it("некорректное выражение — null, а не throw (постфильтр репетитора должен уметь тихо это игнорировать)", () => {
    expect(safeMathEval("2+")).toBeNull();
    expect(safeMathEval("(2+3")).toBeNull();
    expect(safeMathEval("2+*3")).toBeNull();
    expect(safeMathEval("abc")).toBeNull();
    expect(safeMathEval("2 3")).toBeNull(); // два числа подряд без оператора — не valid
  });
});
