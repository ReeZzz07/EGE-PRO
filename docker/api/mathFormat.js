// Формат формул в ответах ИИ-репетитора. Интерфейс (src/components/ui.tsx → TutorText) рисует через KaTeX
// только LaTeX в разметке «скобки со слэшем»: инлайн \( ... \) и блочная \[ ... \]. Модель временами уходит
// на разметку со знаком доллара ($...$ и $$...$$) и тогда ученик видит сырые «$f(x) = a \cdot \cos...$»
// вместо формулы (жалоба 06.10.2026). Кроме вида на экране от формата зависят серверные фильтры утечки
// ответа (prompt.js ищут последнюю формулу именно в скобочной разметке) — на ответе с долларами они
// слепнут. Поэтому ответ модели приводится к одному виду ДО фильтров, а в системный промпт добавлено
// явное правило. Обратные слэши собираем из кода символа, чтобы не путаться с экранированием в строках.
const BS = String.fromCharCode(92);

/** Правило для системного промпта — дописывается ко всем режимам, где модель пишет формулы. */
export const MATH_FORMAT_RULE =
  `\n\nФормулы пиши только в LaTeX и только в таком виде: ${BS}( ... ${BS}) — внутри фразы и ${BS}[ ... ${BS}] — отдельной строкой. ` +
  `Знак доллара ($) для формул не используй. Простые числа, названия и слова пиши обычным текстом, без формул.`;

/**
 * $$...$$ → \[...\], $...$ → \(...\). Одиночный $ считается формулой, только если внутри одной строки, сразу
 * после открывающего нет пробела и перед закрывающим нет пробела («5 $ и 6 $» формулой не считается).
 * Уже скобочные формулы и всё остальное не трогаем.
 */
export function normalizeMath(text) {
  return String(text ?? "")
    .replace(/[$][$]([\s\S]+?)[$][$]/g, (_m, inner) => `${BS}[${inner.trim()}${BS}]`)
    .replace(/[$](?![\s$])([^$\n]+?)(?<![\s$])[$]/g, (_m, inner) => `${BS}(${inner}${BS})`);
}
