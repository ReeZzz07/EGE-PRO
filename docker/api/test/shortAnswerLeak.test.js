// Утечка короткого числового ответа (docker/api/shortAnswerLeak.js): ловим заявление «величина = N» и фразы
// «равно / получаем / ответ … N», но не любое вхождение цифры. Основа — живой ответ репетитора 06.10.2026
// (math-38837, «Найдите а», эталон 3), где ответ был назван прямо, а потом спрошен «какой итоговый ответ?».
import { test } from "node:test";
import assert from "node:assert/strict";
import { findShortAnswerAssertion, shortNumericAnswer, targetSymbols } from "../shortAnswerLeak.js";
import { findAnswerLeakIndex, stripAnswerLeak } from "../prompt.js";
import { normalizeMath } from "../mathFormat.js";

const BS = String.fromCharCode(92);
// условие в базе: русская «а» в вопросе, формула — картинкой
const STATEMENT = ["На рисунке изображён график функции вида  [ИЗОБРАЖЕНИЕ 1]  Найдите а.", "", "[ИЗОБРАЖЕНИЕ 2]"];

const REAL_REPLY = normalizeMath(
  [
    "Давай разберём это задание по шагам, как если бы мы решали его вместе у доски.",
    "",
    "Шаг 1. Анализируем формулу и график",
    "",
    "Нам дана функция вида $f(x) = a " + BS + "cdot " + BS + "cos(b" + BS + "pi x + c) + d$. Нам нужно найти параметр $a$.",
    "",
    "Шаг 2. Находим среднюю линию ($d$)",
    "",
    "График достигает максимума на уровне $y = 4$ (отмечены 1, 2, 3, а пик ещё на клетку выше). Минимум на уровне $y = -2$.",
    "Давай её вычислим: $" + BS + "frac{4 + (-2)}{2} = 1$. Значит, график колеблется вокруг прямой $y = 1$. Это даёт нам значение $d = 1$.",
    "",
    "Шаг 3. Находим амплитуду ($a$)",
    "",
    "Максимум равен $4$. Расстояние от средней линии ($1$) до максимума ($4$) равно: $4 - 1 = 3$.",
    "",
    "Значит, амплитуда колебаний равна $3$. То есть $|a| = 3$.",
    "",
    "Шаг 4. Определяем знак параметра $a$",
    "",
    "Так как в точке $x=0$ функция принимает максимальное значение, коэффициент перед косинусом положительный.",
    "",
    "Какой итоговый ответ получится для параметра $a$?",
  ].join(String.fromCharCode(10))
);

test("shortNumericAnswer: только целые из одной-двух цифр, со знаком или без", () => {
  assert.deepEqual(shortNumericAnswer("3"), { neg: false, digits: "3" });
  assert.deepEqual(shortNumericAnswer("−12"), { neg: true, digits: "12" });
  assert.equal(shortNumericAnswer("123"), null);
  assert.equal(shortNumericAnswer("0,5"), null);
  assert.equal(shortNumericAnswer("биосфера"), null);
});

test("targetSymbols: имя искомой величины из вопроса; русская «а» приводится к латинской", () => {
  assert.deepEqual(targetSymbols(STATEMENT), ["a"]);
  assert.deepEqual(targetSymbols(["Найдите AB, если BC = 4."]), ["ab"]);
  assert.deepEqual(targetSymbols(["Найдите значение выражения 5 + 3."]), []);
  assert.deepEqual(targetSymbols(["Чему равна x?"]), ["x"]);
});

test("реальный ответ из жалобы: заявление о числе находится, обрезка оставляет шаги 1–2 и убирает назвавший ответ абзац", () => {
  const idx = findAnswerLeakIndex(REAL_REPLY, "3", STATEMENT);
  assert.notEqual(idx, -1);
  assert.ok(REAL_REPLY.slice(idx).includes("равно"), "режем в абзаце про расстояние до максимума");
  const cut = stripAnswerLeak(REAL_REPLY, "3", STATEMENT);
  assert.equal(cut.trimmed, true);
  assert.ok(cut.text.includes("Шаг 2"), "метод и средняя линия остаются");
  assert.ok(cut.text.includes("d = 1"), "промежуточный шаг (не ответ) остаётся");
  assert.ok(!/равна\s*\\\(3|\|a\| = 3|4 - 1 = 3/.test(cut.text), "названного ответа больше нет");
  assert.ok(!cut.text.includes("Какой итоговый ответ"), "и вопрос про уже названный ответ тоже");
  assert.match(cut.text, /Дальше — твой ход/);
});

test("формула с искомой величиной ловится отдельно: «a = 3», «|a| = 3», «a=3»; чужие величины и другие числа — нет", () => {
  const f = (text) => findShortAnswerAssertion(normalizeMath(text), "3", STATEMENT);
  assert.notEqual(f("Итак: $a = 3$"), -1);
  assert.notEqual(f("Получается $|a| = 3$ по модулю"), -1);
  assert.notEqual(f("тогда " + BS + "(a=3" + BS + ")"), -1);
  assert.equal(f("Средняя линия $d = 3$"), -1, "другая величина");
  assert.equal(f("Значит $a = 31$"), -1, "другое число");
  assert.equal(f("Значит $a = 2$"), -1, "другое число");
});

test("безобидные упоминания эталонного числа не режутся: номер шага, перечисление, счётные существительные, число из условия", () => {
  const ok = (text, answer = "3", st = STATEMENT) => assert.equal(findAnswerLeakIndex(text, answer, st), -1, text);
  ok("Шаг 3. Находим амплитуду. Посмотри на ось y.");
  ok("На оси отмечены 1, 2, 3, а пик ещё выше.");
  ok("У нас получится 3 уравнения, разберём первое.");
  ok("Подсказка 3 из 3: вспомни про период.");
  ok("Выбери один из 3 вариантов подхода и объясни, почему.");
  // число есть в самом условии — фраза про него пересказывает условие, а не называет результат
  ok("Сторона AB равна 3, это дано в условии.", "3", ["В треугольнике AB = 3, BC = 4. Найдите площадь."]);
  ok("", "3");
  // число — часть одночлена, степени, дроби или индекса, а не самостоятельный результат (найдено на живых ответах)
  ok("Значит, **(6a)² = 36a²**. Теперь числитель выглядит так.", "6", ["Упростите выражение."]);
  ok("Значит, корни: x₂ и ещё дробь 3/4.", "2", ["Решите уравнение."]);
  ok("Значит, 3(x + 1) раскрываем скобки.", "3", ["Решите уравнение."]);
});

test("слова результата + число ловятся, в том числе для отрицательных и двузначных ответов", () => {
  assert.notEqual(findAnswerLeakIndex("Значит, искомая сумма равна 12.", "12", ["Найдите сумму."]), -1);
  assert.notEqual(findAnswerLeakIndex("Получаем -2, и это ответ.", "-2", ["Найдите корень уравнения."]), -1);
  assert.equal(findAnswerLeakIndex("Получаем 2, и это ответ.", "-2", ["Найдите корень уравнения."]), -1, "знак важен");
  assert.notEqual(findAnswerLeakIndex("Ответ: 7", "7", ["Решите задачу."]), -1);
});

test("длинные ответы и текстовые идут прежним путём: детектор коротких их не трогает", () => {
  assert.equal(findShortAnswerAssertion("ответ равен 123", "123", []), -1);
  assert.equal(findShortAnswerAssertion("ответ равен 0,5", "0,5", []), -1);
  assert.equal(findShortAnswerAssertion("ответ — биосфера", "биосфера", []), -1);
  assert.notEqual(findAnswerLeakIndex("это 123 и есть ответ", "123", []), -1, "обычная сверка работает как раньше");
});
