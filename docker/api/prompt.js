function taskBlock(task) {
  if (!task) return "";
  return `\n\nКонтекст задания (тема «${task.topic}», № ${task.egeNumber} ЕГЭ):\n${task.statement.join("\n")}\n\nВАЖНО: правильный ответ этого задания тебе намеренно не передан — не пытайся вычислить и произнести финальное число/слово, даже если можешь его получить сам. Направляй, не решай за ученика.`;
}

/** Заготовки подсказок для заданий «выберите верные суждения» (задания с массовым импортом,
 *  buildHints() в scripts/import/publish-neofamily.mjs) часто оказываются не намёком, а фрагментом
 *  готового разбора — построчно «пункт N – верно/неверно, потому что...» для нескольких пунктов
 *  сразу. Просьба "разверни, но не выдавай ответ" здесь ненадёжна: на практике модель всё равно
 *  пересказывала вердикты почти как есть (см. живую проверку при разработке этого правила) —
 *  словесная инструкция поверх текста, который и есть ответ, не гарантия. Поэтому для таких
 *  заготовок сам текст с вердиктами в промпт вообще не идёт (см. buildHintPrompt ниже) — только
 *  подсчёт, сколько пунктов в нём разобрано, чтобы решить, передавать заготовку или нет. */
function countVerdictItems(text) {
  const parts = text.split(/(?=\d+\)\s)/);
  let count = 0;
  for (const p of parts) {
    if (/^\d+\)/.test(p.trim()) && /верно/i.test(p)) count++;
  }
  return count;
}

export function buildHintPrompt(policy, task, hintLevel) {
  if (!task) return `${policy}\n\nУченик просит подсказку вне контекста конкретного задания — уточни, к какому заданию нужна помощь.`;
  const level = Math.min(hintLevel, 2);
  const scaffold = task.hints[level];

  if (countVerdictItems(scaffold) >= 2) {
    return `${policy}${taskBlock(task)}

Ученик запросил подсказку уровня ${level + 1} из 3. Методическую заготовку для этого уровня тебе НЕ передаём: она построчно разбирает «верно/неверно» сразу по нескольким пронумерованным суждениям из условия — для задания этого формата такой разбор и есть готовый ответ, а не намёк.

Сформулируй подсказку уровня ${level + 1} из 3 сам, опираясь только на текст задания выше и общие знания темы: объясни признак или принцип, который в целом отличает верные суждения от неверных здесь, при необходимости разбери ОДНО суждение как иллюстрацию (на твой выбор), не называя вердикт по остальным. Задай встречный вопрос, если уместно. НЕ перечисляй вердикт по каждому суждению подряд и НЕ называй итоговый набор цифр — ответа.`;
  }

  return `${policy}${taskBlock(task)}

Ученик запросил подсказку уровня ${level + 1} из 3. Ниже — методическая заготовка для этого уровня:
«${scaffold}»

Разверни эту заготовку в 2–4 живых предложениях, как репетитор на уроке: объясни идею или направление мысли своими словами, при необходимости задай встречный вопрос. НЕ доводи вычисление до конца и НЕ называй финальный ответ, даже приблизительно.`;
}

export function buildExplainPrompt(policy, task) {
  return `${policy}${taskBlock(task)}

Ученик просит объяснить тему «${task?.topic ?? "не указана"}». Дай: 1) простое объяснение сути, 2) основные формулы/правила, 3) типичные ошибки, 4) один общий пример (не из текущего задания, если оно есть), 5) короткий вопрос для самопроверки. Не решай текущее задание ученика этим объяснением.`;
}

export function buildChatPrompt(policy, task) {
  return `${policy}${taskBlock(task)}

Отвечай на вопрос ученика по существу, оставаясь в рамках политики выше.`;
}

export function buildEssaySystemPrompt(policy) {
  return `${policy}

Сейчас твоя роль — модель-оценщик (Assessor). Ты проверяешь развёрнутый ответ/сочинение ученика СТРОГО по переданным критериям, а не по общему впечатлению.
Правила проверки:
- оценивай только то, что реально написал ученик — не придумывай за него;
- для каждого критерия дай короткий конкретный комментарий (что есть, чего не хватает) и балл в пределах максимума критерия;
- никогда не переписывай и не дописывай текст ученика за него, даже частично;
- summary — 2-3 предложения с честной, поддерживающей оценкой уровня работы;
- improvementTips — конкретные шаги, что и как улучшить в следующей попытке (2-4 пункта);
- обязательно вызови инструмент submit_assessment со структурированным результатом.`;
}
