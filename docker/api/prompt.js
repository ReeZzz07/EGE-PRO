/** Заготовки подсказок для заданий «выберите верные суждения» (задания с массовым импортом,
 *  buildHints() в scripts/import/publish-neofamily.mjs) часто оказываются не намёком, а фрагментом
 *  готового разбора — построчно «пункт N – верно/неверно, потому что...» для нескольких пунктов
 *  сразу. Просьба "разверни, но не выдавай ответ" здесь ненадёжна: на практике модель всё равно
 *  пересказывала вердикты почти как есть (см. живую проверку при разработке этого правила) —
 *  словесная инструкция поверх текста, который и есть ответ, не гарантия. Поэтому для таких
 *  заготовок сам текст с вердиктами в промпт вообще не идёт (см. buildHintPrompt ниже) — только
 *  подсчёт, сколько пунктов в нём разобрано, чтобы решить, передавать заготовку или нет. */
function countVerdictItems(text) {
  const parts = text.split(/(?=\d+\)\s)/);
  let count = 0;
  for (const p of parts) {
    if (/^\d+\)/.test(p.trim()) && /верно/i.test(p)) count++;
  }
  return count;
}

// Механический фильтр ОТВЕТА модели (в отличие от countVerdictItems выше — тот проверяет
// заготовку ДО отправки в промпт, этот проверяет то, что модель реально написала). Найдено при
// живой проверке: словесный запрет "разбери так подробно максимум ОДИН вариант" (см. DEFAULT_POLICY)
// модель (особенно на бюджетной qwen-max) соблюдает не всегда — на многовариантных заданиях
// («Ударения» и подобные, где нумерованный список — сами варианты ответа, а не только заготовки
// суждений) она иногда проговаривает вердикт «верно/неверно» по каждому пункту подряд, просто не
// печатая финальную строку цифр отдельно. По сути это и есть ответ, только россыпью. Инструкция в
// промпте — первый рубеж, этот фильтр — второй, механический, не зависящий от того, услышала ли
// её модель на этот раз.
const VERDICT_WORD_RE = /верно|правильно|подходит|соответствует/i;
const ITEM_MARKER_RE = /^[ \t]*(?:\d{1,2}|[А-ЯЁ])[.)][ \t]/gm;
// Для заданий с выбором/сопоставлением нескольких пунктов (см. isMultiItemStatement) фильтр шире: модель
// («Клоака действительно участвует…», «Клоака не является…», «Да, клоака…», «### Шаг 2 … точно относится…»)
// выдаёт вердикт по каждому пункту, не используя слов «верно/подходит» — живой пример аудита 24.09.2026.
const VERDICT_WORD_BROAD_RE = /верно|правильно|подходит|соответствует|неверн|действительно|точно относится|не (?:является|участвует|связан\S*|усиливает|относится|входит)|(?:^|[\s—–-])(?:да|нет),/i;
const ITEM_MARKER_BROAD_RE = /^[ \t]*(?:\d{1,2}|[А-ЯЁ])[.)][ \t]|^[ \t]*#{1,4}[ \t]*(?:Шаг|Пункт|Вариант|Суждение|Утверждение)[ \t]*\d+/gm;

/** Возвращает { verdictCount, cutAt } — cutAt — позиция в тексте, с которой начинается ВТОРОЙ
 *  пункт, содержащий вердикт (там текст нужно обрубить), или null, если утечки нет (0 или 1
 *  пункт с вердиктом — один пункт как иллюстрация метода разрешён самой политикой). */
function findVerdictLeak(text, broad = false) {
  const markRe = broad ? ITEM_MARKER_BROAD_RE : ITEM_MARKER_RE;
  const verdictRe = broad ? VERDICT_WORD_BROAD_RE : VERDICT_WORD_RE;
  const marks = [...text.matchAll(markRe)].map((m) => m.index);
  if (marks.length < 2) return { verdictCount: 0, cutAt: null };
  let verdictCount = 0;
  let cutAt = null;
  for (let i = 0; i < marks.length; i++) {
    const start = marks[i];
    const end = i + 1 < marks.length ? marks[i + 1] : text.length;
    if (verdictRe.test(text.slice(start, end))) {
      verdictCount++;
      if (verdictCount === 2) {
        cutAt = start;
        break;
      }
    }
  }
  return { verdictCount, cutAt };
}

/** Обрубает ответ на втором пункте с вердиктом, оставляя первый (разрешённую иллюстрацию метода)
 *  как есть, и подставляет вместо остального явное приглашение доделать самостоятельно — вместо
 *  того, чтобы выкидывать весь ответ целиком (там всё ещё полезная разборка первого варианта).
 *  trimmed:false — вырезать нечего, возвращён исходный текст без изменений. */
export function stripPerItemVerdicts(text, { broad = false } = {}) {
  const { cutAt } = findVerdictLeak(text, broad);
  if (cutAt == null) return { text, trimmed: false };
  const kept = text.slice(0, cutAt).trimEnd();
  return {
    text: `${kept}\n\nОстальные варианты разбери сам(а) по этому же принципу — дальше не буду проговаривать вердикт по каждому из них, иначе это будет готовый ответ, а не подсказка. Попробуй, и если что-то не сойдётся — спроси ещё раз.`,
    trimmed: true,
  };
}

// Второй, отдельный вид утечки готового ответа — не построчный вердикт (см. выше), а прямое
// произнесение всей финальной последовательности цифр для заданий на упорядочивание/соответствие
// ("Установите последовательность...", "Расположите в хронологическом порядке..."). Живой пример
// (bio-75896, реальный ответ модели): по каждому пункту вердикт не проговаривался — фильтр выше
// это пропустил — но в конце модель прямо написала "последовательность должна быть следующей:
// 1-4-3-5-2-6", что и есть готовый ответ для бланка. Ловим либо цепочку через дефис (1-4-3-5-2-6),
// либо список через запятую после двоеточия ("в порядке: 3, 1, 4, 2").
const SEQUENCE_ANSWER_RE = /\b\d{1,2}(?:-\d{1,2}){2,}\b|:\s*\d{1,2}(?:\s*,\s*\d{1,2}){2,}/;

/** Позиция начала предложения, содержащего утечку — обрубаем с начала фразы, а не прямо с цифр,
 *  иначе перед фильтром остаётся висящий обрывок вроде "должна быть следующей: ". null — утечки нет. */
function findSequenceLeak(text) {
  const m = SEQUENCE_ANSWER_RE.exec(text);
  if (!m) return null;
  const before = text.slice(0, m.index);
  const sentenceStart = Math.max(before.lastIndexOf(". "), before.lastIndexOf("!\n"), before.lastIndexOf("?\n"), before.lastIndexOf("\n\n"));
  return sentenceStart === -1 ? 0 : sentenceStart + 2;
}

/** Обрубает ответ с начала предложения, где называется готовая последовательность цифр, и
 *  подставляет приглашение доделать самостоятельно. trimmed:false — исходный текст без изменений. */
export function stripSequenceAnswer(text) {
  const cutAt = findSequenceLeak(text);
  if (cutAt == null) return { text, trimmed: false };
  const kept = text.slice(0, cutAt).trimEnd();
  return {
    text: `${kept}\n\nСаму последовательность запиши сам(а) — я специально не называю готовый порядок, чтобы это был твой ответ, а не мой. Попробуй, и если не сойдётся — спроси ещё раз.`,
    trimmed: true,
  };
}

// Третий вид утечки — не построчный вердикт и не готовая последовательность (см. выше), а прямое
// СЛОВЕСНОЕ подтверждение, что только что вычисленное число и есть финальный ответ ("Мы нашли, что
// cos(x) = -0,6. Это и есть ответ на задание!"). Живые примеры на математике и физике (задания с
// ОДНИМ конкретным числовым ответом) показали: модель регулярно доводит вычисление до самого конца
// и явно это провозглашает, несмотря на прямой запрет в DEFAULT_POLICY/buildExplainPrompt.
// ВАЖНО, в отличие от двух фильтров выше — это НЕ полноценное решение. Сама утечка (формула с
// настоящим числом, например "cos(x) = -0,6") обычно уже стоит ВЫШЕ этой фразы в тексте, а без
// знания правильного ответа задания (для большинства заданий он вообще не передаётся в ИИ-подсистему,
// см. TASK_ANSWERS в server.js) мы не можем механически отличить "формулу, из которой прямо следует
// ответ" от легитимного предпоследнего шага — синтаксически они не различаются. Этот фильтр вырезает
// только явное словесное подтверждение (снижает уверенность утечки и убирает самый однозначный
// сигнал), но не гарантирует, что число выше в тексте не тот же ответ. Основная защита — правка
// формулировки промпта (требование заканчивать вопросом, а не фактом), этот фильтр — доп. рубеж.
const ANSWER_DECLARATION_RE =
  /это\s+(?:и\s+)?есть\s+(?:правильный\s+|итоговый\s+|финальный\s+)?ответ|это\s+ответ\s+(?:на|к)\s+\S+|вот\s+(?:и\s+)?(?:твой\s+|ваш\s+)?ответ|таков\s+(?:и\s+)?ответ|искомы[йх]\s+ответ|получаем\s+ответ/i;

function findAnswerDeclaration(text) {
  const m = ANSWER_DECLARATION_RE.exec(text);
  if (!m) return null;
  const before = text.slice(0, m.index);
  const sentenceStart = Math.max(before.lastIndexOf(". "), before.lastIndexOf("!\n"), before.lastIndexOf("?\n"), before.lastIndexOf("\n\n"));
  return sentenceStart === -1 ? 0 : sentenceStart + 2;
}

/** Обрубает ответ с начала предложения, где модель словесно подтверждает финальный ответ, и
 *  подставляет приглашение доделать самостоятельно. trimmed:false — исходный текст без изменений.
 *  См. комментарий выше про частичность этого фильтра. */
export function stripAnswerDeclaration(text) {
  const cutAt = findAnswerDeclaration(text);
  if (cutAt == null) return { text, trimmed: false };
  const kept = text.slice(0, cutAt).trimEnd();
  return {
    text: `${kept}\n\nПоследний шаг — твой: доведи вычисление до конца сам(а) и сверься. Если что-то не сойдётся — спроси ещё раз.`,
    trimmed: true,
  };
}

// Четвёртый, самый частый и самый неоднозначный вид утечки: модель доводит ПОСЛЕДНЮЮ формулу в
// ответе до чистого числа ("d = 4 × 3", затем "d = 12") — без единого словесного подтверждения
// ("это ответ"), просто как "ещё один шаг вычисления", даже когда следом сама же формально
// спрашивает "какой результат получится?" (вопрос, потерявший смысл — ответ уже назван). Живой
// пример на задании про куб: три формулы подряд "d = 4√3·√3" → "d = 4×3" → "d = 12", и только
// ПОСЛЕДНЯЯ — голое число.
//
// Эвристика: если ПОСЛЕДНЯЯ формула \[...\]/\(...\) во всём тексте имеет вид "что угодно = <голое
// число>" (без переменных, корней или операций в правой части) — считаем это вычисленным финальным
// результатом. Это ловит форму, а не смысл: у легитимного предпоследнего шага (когда модель следует
// инструкции и останавливается ДО вычисления) правая часть обычно НЕ голое число — там остаётся
// операция (см. "|Δx| = |0|", "d = (5√3)√3" — не тронуты этим фильтром). Но если задание простое
// ("найдите X, если...") и модель доходит до чистого "X = N" на последнем шаге, фильтр сработает
// даже в случаях, когда это на самом деле легитимный промежуточный итог, а не финальный ответ —
// такой ложноположительный срез стоит меньше, чем реальная утечка ответа.
const BARE_NUMBER_RESULT_RE = /^[^=\n]+=\s*[-−]?\d+(?:[.,]\d+)?\s*$/;
const FORMULA_BLOCK_RE = /\\\[([\s\S]*?)\\\]|\\\(([\s\S]+?)\\\)/g;

function findFinalBareNumberFormula(text) {
  const matches = [...text.matchAll(FORMULA_BLOCK_RE)];
  if (matches.length === 0) return null;
  const last = matches[matches.length - 1];
  const latex = (last[1] ?? last[2] ?? "").trim();
  if (!BARE_NUMBER_RESULT_RE.test(latex)) return null;
  return last.index;
}

/** Обрубает ответ с начала последней формулы, если она сводится к голому числу (см. комментарий
 *  выше про эвристику и её ограничения), и подставляет приглашение доделать самостоятельно. */
export function stripFinalBareNumberFormula(text) {
  const cutAt = findFinalBareNumberFormula(text);
  if (cutAt == null) return { text, trimmed: false };
  const kept = text.slice(0, cutAt).trimEnd();
  return {
    text: `${kept}\n\nПодставь свои числа в эту формулу и вычисли сам(а) — я специально не довожу это до готового числа. Если что-то не сойдётся — спроси ещё раз.`,
    trimmed: true,
  };
}

// ─────────────── утечка ТОЧНОГО ответа (по эталону из БД) ───────────────
// Остальные фильтры выше — эвристики по ФОРМЕ ответа модели. Для заданий из БД эталонный ответ известен
// серверу (tasks.answer), но раньше сверки с ним не было вовсе (leaksAnswer в server.js работает только
// по нескольким «статическим» заданиям). Здесь — прямая сверка: если готовый ответ прозвучал в тексте,
// ответ обрубается с начала абзаца. Очень короткие ответы (одна-две цифры) не сверяем — они постоянно
// встречаются в промежуточных вычислениях; то же для всего, что уже есть в самом условии.
const norm = (s) => String(s).toLowerCase().replace(/ё/g, "е");
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Есть ли в условии нумерованный/буквенный список пунктов (выбор нескольких, соответствие). */
export function isMultiItemStatement(statement = []) {
  const marks = statement.filter((l) => /^\s*(?:\d{1,2}|[А-ЯЁA-F])[.)]\s/.test(l)).length;
  return marks >= 3 || /(?:^|\s)1\)[\s\S]*\s2\)/.test(statement.join("\n"));
}

function answerPatterns(answer, statement) {
  const raw = String(answer ?? "").trim();
  if (!raw) return [];
  const a = norm(raw).replace(/−|–/g, "-");
  if (/^-?\d+(?:[.,]\d+)?$/.test(a)) {
    const neg = a.startsWith("-");
    const body = neg ? a.slice(1) : a;
    const hasDecimal = /[.,]/.test(body);
    const isCode = /^\d{2,8}$/.test(body) && !neg && isMultiItemStatement(statement);
    if (!hasDecimal && !isCode && body.length < 3) return []; // «7», «42» — слишком частые числа
    const digits = escRe(body).replace(/[.,]/, "[.,]");
    const pats = [new RegExp(`(?<![\\d,.\\-−–])${neg ? "[-−–]\\s?" : ""}${digits}(?![\\d]|[.,]\\d)`, "i")];
    if (isCode) pats.push(new RegExp(`(?<!\\d)${body.split("").join("[\\s,;–\\-]{1,3}(?:и\\s+)?")}(?!\\d)`, "i"));
    return pats;
  }
  // текстовый ответ; варианты через «/» (как в банке: «обмен веществ/метаболизм»)
  return raw
    .split("/")
    .map((v) => norm(v).trim())
    .filter((v) => v.length >= 4 && !/^\d+$/.test(v))
    .map((v) => {
      const words = v.split(/\s+/);
      if (words.length === 1 && v.length >= 6) return new RegExp(`(?<![а-яa-z0-9])${escRe(v.slice(0, v.length - 2))}[а-яa-z]*`, "i");
      // словоформы: у слов от 5 букв отбрасываем окончание («обмен веществ» найдётся и в «обмена веществ»)
      const stem = (w) => (w.length >= 5 ? `${escRe(w.slice(0, w.length - 2))}[а-яa-z]*` : `${escRe(w)}(?![а-яa-z0-9])`);
      return new RegExp(`(?<![а-яa-z0-9])${words.map(stem).join("\\s+")}`, "i");
    });
}

/** Позиция первого появления эталонного ответа в тексте или -1. Не считается утечкой то, что уже
 *  есть в самом условии задания. */
export function findAnswerLeakIndex(text, answer, statement = []) {
  const pats = answerPatterns(answer, statement);
  if (!pats.length) return -1;
  const stmt = norm(statement.join("\n"));
  const t = norm(text);
  let best = -1;
  for (const re of pats) {
    if (re.test(stmt)) continue;
    const m = re.exec(t);
    if (m && (best === -1 || m.index < best)) best = m.index;
  }
  return best;
}

/** Обрубает ответ с начала абзаца, где прозвучал эталонный ответ, и подставляет приглашение доделать
 *  самому. trimmed:false — утечки нет, текст не менялся. */
export function stripAnswerLeak(text, answer, statement = []) {
  const idx = findAnswerLeakIndex(text, answer, statement);
  if (idx === -1) return { text, trimmed: false };
  const para = text.lastIndexOf("\n\n", idx);
  const kept = text.slice(0, para === -1 ? 0 : para).trimEnd();
  const note = "Дальше — твой ход: последние шаги и сам ответ я не называю. Доведи решение до конца сам(а), и если что-то не сойдётся — спроси ещё раз.";
  return { text: kept ? `${kept}\n\n${note}` : `Я уже подошёл слишком близко к готовому ответу, поэтому остановлюсь. ${note}`, trimmed: true };
}

/** Сбой модели: иероглифы/кана/хангыль в русскоязычном ответе или утёкшие служебные токены шаблона чата
 *  (`<|im_start|>` и т.п.). Живой пример на qwen-max: подсказка по химии ушла абзацами на китайском. */
export function hasModelGlitch(text) {
  return /[぀-ヿ㐀-䶿一-鿿가-힯]/.test(text) || /<\|[a-z_]+\|>/i.test(text);
}

// Уровни подсказок нарочно РАЗНЫЕ по глубине — раньше все три сводились к одной и той же общей
// формулировке "вспомни правило" независимо от уровня (см. живую проверку, где 1/2/3 отличались
// только парой слов). Уровень 3 должен быть настоящей опорой для того, кто застрял всерьёз, а не
// той же наводкой, что и уровень 1.
const HINT_LEVEL_GUIDANCE = [
  `Это САМАЯ ЛЁГКАЯ наводка (уровень 1 из 3): назови тему/правило, которое нужно применить, и укажи, на какую именно часть условия задания стоит посмотреть внимательнее. Не описывай сам метод решения и не упоминай числа/слова/варианты из условия — только направление мысли.`,
  `Это подсказка построже (уровень 2 из 3): объясни сам метод или формулу решения и покажи, как его применить ИМЕННО к данным этого задания — называй реальные числа, слова или варианты из условия. Доведи рассуждение до предпоследнего шага, но не выполняй последнее вычисление и не называй итоговое число/слово — сформулируй его как вопрос ученику, а не как факт.`,
  `Это САМАЯ ПОДРОБНАЯ подсказка (уровень 3 из 3, для тех, кто застрял всерьёз): пройди почти всё решение шаг за шагом, используя конкретные данные из условия этого задания, как если бы объяснял ученику у доски. Остановись ровно перед последним действием — обозначь, какую именно операцию нужно сделать последней, оформи это как вопрос ученику, но не выполняй её сам и не проговаривай результат («получаем», «это и есть ответ»).`,
];

export function buildHintPrompt(policy, task, hintLevel, ctx = {}) {
  if (!task) return `${policy}\n\nУченик просит подсказку вне контекста конкретного задания — уточни, к какому заданию нужна помощь.`;
  const level = Math.min(hintLevel, 2);
  const scaffold = task.hints[level];
  const guidance = HINT_LEVEL_GUIDANCE[level];
  const block = taskBlock(task, ctx);

  if (countVerdictItems(scaffold) >= 2) {
    return `${policy}${block}

Ученик запросил подсказку уровня ${level + 1} из 3. ${guidance}

Методическую заготовку для этого уровня тебе НЕ передаём: она построчно разбирает «верно/неверно» сразу по нескольким пронумерованным суждениям из условия — для задания этого формата такой разбор и есть готовый ответ, а не намёк. Сформулируй подсказку сам, опираясь на текст задания выше: объясни признак или принцип, который в целом отличает верные суждения от неверных здесь, при необходимости разбери ОДНО суждение как иллюстрацию (на твой выбор), не называя вердикт по остальным. НЕ перечисляй вердикт по каждому суждению подряд и НЕ называй итоговый набор цифр — ответа.`;
  }

  // Заготовка методиста — фрагмент готового разбора. Для заданий «выберите/сопоставьте несколько пунктов»
  // (уровни 2–3) и для любых заданий, где в заготовке прямо стоит эталонный ответ, модель пересказывала её
  // почти дословно (живая проверка: «верные варианты — 2, 3 и 6», «(А) — открытый, (Б) — Иркутский…»).
  // Поэтому такую заготовку в промпт вообще не передаём — как и вердикты выше.
  const multiItem = isMultiItemStatement(task.statement) && level >= 1;
  const carriesAnswer = !!scaffold && !!ctx.answer && findAnswerLeakIndex(scaffold, ctx.answer, task.statement) !== -1;
  if (scaffold && (multiItem || carriesAnswer)) {
    return `${policy}${block}

Ученик запросил подсказку уровня ${level + 1} из 3. ${guidance}

Методическую заготовку для этого уровня тебе НЕ передаём: она содержит готовый разбор или ответ этого задания. Сформулируй подсказку сам, опираясь на текст задания выше: назови правило или метод и покажи, как он применяется к данным условия. НЕ называй итоговый ответ, НЕ перечисляй вердикт по каждому пункту подряд и не подставляй слова/номера, которые и есть ответ.`;
  }

  return `${policy}${block}

Ученик запросил подсказку уровня ${level + 1} из 3. ${guidance}${
    scaffold
      ? `\n\nЗаготовка методиста для этого уровня (опора, не пересказывай один в один — разверни своими словами с реальными данными задания): «${scaffold}»`
      : ""
  }`;
}

export function buildExplainPrompt(policy, task, ctx = {}) {
  return `${policy}${taskBlock(task, ctx)}

Ученик просит подробно объяснить, как решать это задание — веди себя как репетитор у доски: разбери условие по шагам, используя реальные числа, слова, варианты и данные из условия задания выше (не абстрактную тему в отрыве от него). Если это поможет объяснить сам метод, можешь для иллюстрации коротко привести аналогичный пример на других числах/словах — но большая часть объяснения должна быть про ЭТО задание. Дойди до момента, когда до ответа остаётся ровно ОДНО действие (вычислить выражение, выбрать знак, округлить, подставить последние числа) — и сформулируй именно ЕГО как явный вопрос ученику, а не как факт. Не выполняй это последнее действие сам и не проговаривай его результат («получаем», «это и есть ответ», «равно...»): ответ должен заканчиваться вопросом или прямой инструкцией «попробуй сам(а)», а не завершённой формулой с названным числом.`;
}

