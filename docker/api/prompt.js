/** Что из приложенного к заданию модель НЕ видит: аудиозапись (модели не слышат) и растровые
 *  картинки (графики, схемы, карты), если провайдер/модель без vision. Формулы Wiris (.svg) идут
 *  текстом (см. taskImages.js) и сюда не попадают. */
export function describeUnseenMedia(task, canSeeImages) {
  const media = task?.media ?? [];
  const audio = media.some((m) => /\.mp3$/i.test(m.storage_path ?? ""));
  const pictures = media.some((m) => !/\.(svg|mp3)$/i.test(m.storage_path ?? ""));
  const parts = [];
  if (audio) parts.push("аудиозапись (ты не можешь её слушать)");
  if (pictures && !canSeeImages) parts.push("рисунок, график, схема или карта (ты их не видишь)");
  return parts;
}

