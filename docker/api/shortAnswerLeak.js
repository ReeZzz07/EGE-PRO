// Утечка КОРОТКОГО числового ответа (одна-две цифры: «3», «12», «-2»). Прямая сверка с эталоном (prompt.js →
// findAnswerLeakIndex) такие ответы не проверяет: числа 1–99 постоянно встречаются в промежуточных
// вычислениях, номерах шагов и перечислениях, любое «найдено вхождение» резало бы почти каждую подсказку.
// Но именно короткие числа — самый частый ответ в математике и физике, и репетитор регулярно «называет» их
// прямо в тексте. Живой пример 06.10.2026 (задание math-38837, «Найдите a», ответ 3): «Расстояние от средней
// линии до максимума равно: 4 − 1 = 3 … амплитуда равна 3, знак положительный» — и после этого вопрос
// «какой итоговый ответ получится?», хотя ответ уже назван. Поэтому здесь ловится не число само по себе, а
// ЗАЯВЛЕНИЕ о нём — два вида, оба достаточно узкие:
//  1) формула «искомая величина = N»: имя величины берётся из вопроса задания («Найдите a»), допускается |a|;
//  2) фраза со словом результата («равно», «получаем», «ответ», «итого», «значит», «искомое»…) и числом в
//     том же предложении, если после числа нет существительного («получим 2 уравнения» — не ответ).
// Ложные срабатывания возможны (промежуточный результат случайно равен ответу) — цена такого среза мала:
// ученик получает обрезанную подсказку и может спросить ещё раз; пропущенная утечка стоит дороже.
const norm = (s) => String(s ?? "").toLowerCase().replace(/ё/g, "е");

// Кириллические буквы, неотличимые от латинских: в условии «Найдите а» может стоять русская «а», а модель
// пишет латинскую (и наоборот) — имя величины сравниваем в одном алфавите. Замена один символ в один,
// поэтому позиции в тексте не сдвигаются.
const LOOKALIKE = { а: "a", в: "b", с: "c", е: "e", к: "k", м: "m", н: "h", о: "o", р: "p", т: "t", х: "x", у: "y" };
const toLatin = (s) => s.replace(/[авсекмнортху]/g, (ch) => LOOKALIKE[ch]);

/** «3» / «−12» → { neg, digits }; всё остальное (дроби, длинные числа, слова) — null: их покрывает обычная сверка. */
export function shortNumericAnswer(answer) {
  const m = /^(-?)(\d{1,2})$/.exec(norm(answer).trim().replace(/[−–]/g, "-"));
  return m ? { neg: m[1] === "-", digits: m[2] } : null;
}

const TARGET_RE =
  /(?:найд[иё]те|определите|вычислите|найти|чему равн[аоы]?|укажите)\s+(?:значени[яе]\s+|величину\s+|параметр\s+|коэффициент\s+)?([a-z]{1,2}|[а-я])(?![a-zа-я])/g;

/** Имена искомых величин из вопроса задания: «Найдите a», «Найдите AB» → ["a", "ab"]. */
export function targetSymbols(statement = []) {
  const text = norm((Array.isArray(statement) ? statement : [statement]).join(" "));
  const out = new Set();
  for (const m of text.matchAll(TARGET_RE)) out.add(toLatin(m[1]));
  return [...out];
}

const RESULT_VERBS = "(?:равн[а-я]*|составля[а-я]*|получ[а-я]*|будет|выход[а-я]*|ответ[а-я]*|итог[а-я]*|значит|итак|искомо[а-я]*)";

/** Позиция первого заявления о коротком числовом ответе в тексте или -1. */
export function findShortAnswerAssertion(text, answer, statement = []) {
  const a = shortNumericAnswer(answer);
  if (!a) return -1;
  const t = norm(text);
  const latin = toLatin(t);
  const stmt = norm((Array.isArray(statement) ? statement : [statement]).join("\n"));
  const sign = a.neg ? "[-−–]\\s?" : "(?<![-−–])";
  // число — самостоятельное: не часть одночлена «6a», степени «6²», дроби «3/4», коэффициента «3(x+1)», индекса «x₂»
  const num = `(?<![\\d,.a-zа-я_^₀-₉])${sign}${a.digits}(?!\\d|[.,]\\d|[a-zа-я²³^_*/(])`;
  let best = -1;
  const take = (re, source) => {
    const m = new RegExp(re, "i").exec(source);
    if (m && (best === -1 || m.index < best)) best = m.index;
  };

  // 2) слово результата + число в том же предложении, дальше не слово («получим 2 уравнения» не считается);
  //    если это число есть в самом условии, фраза про него — пересказ условия, а не результат
  if (!new RegExp(num).test(stmt)) {
    take(`(?<![а-яa-z])${RESULT_VERBS}[^.!?\\x0A]{0,50}?${num}(?![ \\t]*[а-я]{3,})`, t);
  }

  // 1) «искомая величина = N», в том числе |a| = N
  for (const s of targetSymbols(statement)) {
    take(`(?<![a-z0-9_])(?:\\|\\s*)?${s}(?:\\s*\\|)?\\s*=\\s*[±]?\\s*${a.digits}(?!\\d|[.,]\\d)`, latin);
  }
  return best;
}
