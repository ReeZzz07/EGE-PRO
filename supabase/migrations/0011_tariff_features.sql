-- Редактируемый список преимуществ тарифа (то, что показывается со значком-галочкой на публичной
-- странице тарифов) — раньше три строки собирались в коде из subjects_count/daily_ai_limit и
-- статичного текста, админ их поправить не мог. Теперь это произвольный список строк, который
-- задаёт админ (AdminTariffs.tsx), а Tariffs.tsx просто выводит его как есть.
alter table public.tariffs add column features jsonb not null default '[]'::jsonb;

