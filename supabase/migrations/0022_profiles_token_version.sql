-- JWT-токены подписывались на 30 дней (см. docker/api/server.js signToken) без какого-либо
-- способа отозвать их раньше срока — смена пароля не обесценивала уже выданные токены, так что
-- украденный (или просто оставленный в чужом браузере) токен продолжал работать месяц независимо
-- от того, что владелец аккаунта сменил пароль именно из-за подозрения на утечку.
-- token_version, зашитый в каждый новый токен (см. signToken) и сверяемый на каждый запрос (см.
-- authMiddleware), даёт реальную отмену: смена пароля увеличивает значение в БД — все токены,
-- выпущенные до этого момента, сразу перестают проходить проверку, сколько бы им ещё не оставалось.
alter table public.profiles add column token_version int not null default 0;

-- Пишет token_version только доверенный api-сервис (подключается к Postgres как суперпользователь,
-- минуя RLS/PostgREST — см. docker/api/db.js) при смене пароля. Через обычную authenticated-роль
-- (прямые запросы к PostgREST) этот столбец трогать не нужно и не должно быть можно — иначе смысл
-- отмены токена терялся бы, если бы его можно было откатить тем же запросом, что его провоцирует.
revoke update (token_version) on public.profiles from authenticated;
