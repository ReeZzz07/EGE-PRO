-- Шкала перевода первичных баллов в тестовые — по решениям комиссии Рособрнадзора она меняется
-- каждый год и по каждому предмету, и официально утверждается только весной года сдачи (после
-- досрочного этапа), поэтому не может быть жёстко зашита в код. Универсальная таблица вместо
-- этого: одна строка = один первичный балл конкретного предмета в конкретном году → его вторичный
-- (тестовый) балл. Админ правит/добавляет годы через AdminScoreScales.tsx, ничего не пересобирая.
--
-- Математика базового уровня — исключение по смыслу, не по схеме: вузы её не принимают, итог —
-- школьная оценка 2-5, а не 100-балльная шкала. Строки те же (primary_score → secondary_score),
-- просто secondary_score здесь означает оценку, а не тестовый балл (см. подпись на экране в
-- ProfileView.tsx/MockExam.tsx — там разбирается по subject === 'math_base').
create table public.score_scales (
  subject text not null check (subject = any (array['math','rus','inf','fiz','soc','bio','eng','geo','chem','hist','lit','math_base'])),
  year int not null,
  primary_score int not null check (primary_score >= 0),
  secondary_score int not null check (secondary_score >= 0),
  primary key (subject, year, primary_score)
);

alter table public.score_scales enable row level security;

-- читают все, даже анонимы — это справочные данные уровня лендинга/тарифов, не приватные
create policy "score_scales_select_all" on public.score_scales
  for select
  using (true);

-- пишут только администраторы
create policy "score_scales_admin_write" on public.score_scales
  for all to authenticated
  using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin))
  with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin));

