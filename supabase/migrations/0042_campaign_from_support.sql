-- Рассылки из админки: письмо можно отправить от имени поддержки (support@), чтобы ответы получателей
-- приходили в общий ящик поддержки, а не на служебный noreply@. Нужно, например, для опроса тех, кто начал
-- оплату и не завершил её («что помешало?»): ответ на такое письмо — и есть результат рассылки.
alter table public.email_campaigns add column from_support boolean not null default false;
