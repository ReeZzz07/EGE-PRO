update public.content_blocks
   set data = jsonb_set(
         jsonb_set(
           jsonb_set(
             coalesce(data, '{}'::jsonb),
             '{perSubjectNote}',
             to_jsonb($t$поштучно — от 1290 ₽ за предмет на 30 дней$t$::text),
             true
           ),
           '{subtitle}',
           to_jsonb($t$ЕГЭ·ПРО — онлайн-тренажёр ЕГЭ: диагностика 8–12 заданий за 7–10 минут, банк заданий в формате открытого банка ФИПИ, персональный план и ИИ-репетитор без готового ответа. На всех тарифах этот набор есть; платные пакеты отличаются числом предметов и лимитом ИИ. Оплата разовая на 30 дней через ЮKassa (карта/СБП), без автопродления; родитель может оплатить по ссылке.$t$::text),
           true
         ),
         '{faq}',
         $j$[
           {"q":"С какой суммы начинается платный доступ?","a":"Платный тариф «Аттестат» — 1990 ₽ за 30 дней (2 предмета, ИИ без лимита). Есть бесплатный тариф «Попробовать»."},
           {"q":"Есть ли автопродление?","a":"Нет. Оплата разовая через ЮKassa, карта не сохраняется для автосписаний."},
           {"q":"Может ли оплатить родитель?","a":"Да. Ученик отправляет ссылку на оплату из аккаунта — подробности на странице «Родителям»."},
           {"q":"Что входит во все тарифы?","a":"Диагностика 8–12 заданий за 7–10 минут, персональный план, банк заданий формата открытого банка ФИПИ и ИИ-репетитор без готового ответа. Отличаются число предметов и лимит обращений к ИИ."}
         ]$j$::jsonb,
         true
       ),
       updated_at = now()
 where key = 'tariffsPage';
